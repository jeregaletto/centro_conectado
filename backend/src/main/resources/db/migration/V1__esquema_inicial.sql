-- Centro Conectado · esquema inicial
-- SQL portable entre PostgreSQL y H2 (MODE=PostgreSQL).

CREATE TABLE sectores (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(40)  NOT NULL UNIQUE,
    nombre       VARCHAR(120) NOT NULL,
    descripcion  VARCHAR(500),
    referente_id BIGINT
);

CREATE TABLE usuarios (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario               VARCHAR(40)  NOT NULL UNIQUE,
    password_hash         VARCHAR(100) NOT NULL,
    nombre                VARCHAR(80)  NOT NULL,
    apellido              VARCHAR(80)  NOT NULL,
    email                 VARCHAR(150),
    telefono              VARCHAR(40),
    interno               VARCHAR(20),
    puesto                VARCHAR(80)  NOT NULL,
    rol                   VARCHAR(30)  NOT NULL,
    sector_id             BIGINT       NOT NULL REFERENCES sectores (id),
    activo                BOOLEAN      NOT NULL DEFAULT TRUE,
    debe_cambiar_password BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en             TIMESTAMP    NOT NULL
);
CREATE INDEX idx_usuarios_sector ON usuarios (sector_id);

ALTER TABLE sectores
    ADD CONSTRAINT fk_sectores_referente FOREIGN KEY (referente_id) REFERENCES usuarios (id);

-- Avisos / novedades / cambios de horario
CREATE TABLE avisos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(150)  NOT NULL,
    cuerpo           VARCHAR(4000) NOT NULL,
    tipo             VARCHAR(20)   NOT NULL,
    fijado           BOOLEAN       NOT NULL DEFAULT FALSE,
    requiere_lectura BOOLEAN       NOT NULL DEFAULT FALSE,
    autor_id         BIGINT        NOT NULL REFERENCES usuarios (id),
    publicado_en     TIMESTAMP     NOT NULL,
    vigente_hasta    TIMESTAMP     NOT NULL,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_avisos_vigencia ON avisos (activo, vigente_hasta);

CREATE TABLE aviso_sectores (
    aviso_id  BIGINT NOT NULL REFERENCES avisos (id) ON DELETE CASCADE,
    sector_id BIGINT NOT NULL REFERENCES sectores (id),
    PRIMARY KEY (aviso_id, sector_id)
);

CREATE TABLE aviso_lecturas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aviso_id   BIGINT    NOT NULL REFERENCES avisos (id) ON DELETE CASCADE,
    usuario_id BIGINT    NOT NULL REFERENCES usuarios (id),
    leido_en   TIMESTAMP NOT NULL,
    CONSTRAINT uq_aviso_lectura UNIQUE (aviso_id, usuario_id)
);

-- Agenda
CREATE TABLE eventos (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo               VARCHAR(150)  NOT NULL,
    descripcion          VARCHAR(2000),
    tipo                 VARCHAR(20)   NOT NULL,
    lugar                VARCHAR(150),
    inicio               TIMESTAMP     NOT NULL,
    fin                  TIMESTAMP     NOT NULL,
    recordatorio_minutos INTEGER,
    recordatorio_enviado BOOLEAN       NOT NULL DEFAULT FALSE,
    autor_id             BIGINT        NOT NULL REFERENCES usuarios (id),
    creado_en            TIMESTAMP     NOT NULL
);
CREATE INDEX idx_eventos_inicio ON eventos (inicio);

CREATE TABLE evento_sectores (
    evento_id BIGINT NOT NULL REFERENCES eventos (id) ON DELETE CASCADE,
    sector_id BIGINT NOT NULL REFERENCES sectores (id),
    PRIMARY KEY (evento_id, sector_id)
);

-- Notificaciones in-app
CREATE TABLE notificaciones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT        NOT NULL REFERENCES usuarios (id),
    tipo       VARCHAR(30)   NOT NULL,
    titulo     VARCHAR(150)  NOT NULL,
    mensaje    VARCHAR(1000) NOT NULL,
    link       VARCHAR(255),
    leida      BOOLEAN       NOT NULL DEFAULT FALSE,
    creada_en  TIMESTAMP     NOT NULL
);
CREATE INDEX idx_notificaciones_usuario ON notificaciones (usuario_id, leida);

-- Mi puesto
CREATE TABLE tareas_puesto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id   BIGINT       NOT NULL REFERENCES sectores (id),
    puesto      VARCHAR(80),
    titulo      VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    icono       VARCHAR(40)  NOT NULL,
    frecuencia  VARCHAR(10)  NOT NULL,
    orden       INTEGER      NOT NULL DEFAULT 0,
    activa      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE tareas_registro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id      BIGINT    NOT NULL REFERENCES tareas_puesto (id),
    usuario_id    BIGINT    NOT NULL REFERENCES usuarios (id),
    periodo       DATE      NOT NULL,
    completada_en TIMESTAMP NOT NULL,
    CONSTRAINT uq_tarea_registro UNIQUE (tarea_id, usuario_id, periodo)
);

-- Pedidos e interconsultas entre áreas
CREATE TABLE pedidos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(20) UNIQUE,
    tipo              VARCHAR(20)   NOT NULL,
    asunto            VARCHAR(150)  NOT NULL,
    detalle           VARCHAR(2000) NOT NULL,
    prioridad         VARCHAR(10)   NOT NULL,
    estado            VARCHAR(20)   NOT NULL,
    sector_origen_id  BIGINT        NOT NULL REFERENCES sectores (id),
    sector_destino_id BIGINT        NOT NULL REFERENCES sectores (id),
    creado_por_id     BIGINT        NOT NULL REFERENCES usuarios (id),
    asignado_a_id     BIGINT REFERENCES usuarios (id),
    plazo             TIMESTAMP     NOT NULL,
    creado_en         TIMESTAMP     NOT NULL,
    actualizado_en    TIMESTAMP     NOT NULL,
    cerrado_en        TIMESTAMP
);
CREATE INDEX idx_pedidos_destino ON pedidos (sector_destino_id, estado);
CREATE INDEX idx_pedidos_origen ON pedidos (sector_origen_id, estado);

CREATE TABLE pedido_movimientos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT    NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    usuario_id      BIGINT    NOT NULL REFERENCES usuarios (id),
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20),
    comentario      VARCHAR(1000),
    creado_en       TIMESTAMP NOT NULL
);

-- Buzón (consultas, sugerencias, reclamos). Si anonimo = TRUE, autor_id y sector_id quedan en NULL.
CREATE TABLE buzon_mensajes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_seguimiento VARCHAR(16)   NOT NULL UNIQUE,
    tipo               VARCHAR(20)   NOT NULL,
    asunto             VARCHAR(150)  NOT NULL,
    cuerpo             VARCHAR(4000) NOT NULL,
    anonimo            BOOLEAN       NOT NULL,
    autor_id           BIGINT REFERENCES usuarios (id),
    sector_id          BIGINT REFERENCES sectores (id),
    estado             VARCHAR(20)   NOT NULL,
    plazo_respuesta    TIMESTAMP     NOT NULL,
    respuesta          VARCHAR(4000),
    respondido_por_id  BIGINT REFERENCES usuarios (id),
    respondido_en      TIMESTAMP,
    creado_en          TIMESTAMP     NOT NULL
);

-- Biblioteca
CREATE TABLE documentos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(150) NOT NULL,
    descripcion      VARCHAR(500),
    categoria        VARCHAR(30)  NOT NULL,
    url              VARCHAR(500) NOT NULL,
    sector_id        BIGINT REFERENCES sectores (id),
    version          VARCHAR(20),
    publicado_por_id BIGINT       NOT NULL REFERENCES usuarios (id),
    publicado_en     TIMESTAMP    NOT NULL,
    vigente_hasta    TIMESTAMP    NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Quién es quién: "a quién acudir"
CREATE TABLE a_quien_acudir (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema        VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    sector_id   BIGINT       NOT NULL REFERENCES sectores (id),
    contacto_id BIGINT REFERENCES usuarios (id),
    orden       INTEGER      NOT NULL DEFAULT 0
);
